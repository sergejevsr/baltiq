const LANG_META = {
  ru: { label: "Русский", locale: "ru-RU" },
  lv: { label: "Latviešu", locale: "lv-LV" },
  lt: { label: "Lietuvių", locale: "lt-LT" },
  et: { label: "Eesti", locale: "et-EE" },
  en: { label: "English", locale: "en-GB" },
};

function domainDefaultLang() {
  const host = (location.hostname || "").toLowerCase();
  if (host.endsWith(".lv") || host.includes(".lv.")) return "lv";
  if (host.endsWith(".lt") || host.includes(".lt.")) return "lt";
  if (host.endsWith(".ee") || host.includes(".ee.")) return "et";
  return "ru";
}

function langOrder() {
  const first = domainDefaultLang();
  const rest = ["lv", "lt", "et", "ru", "en"].filter((x) => x !== first);
  return [first, ...rest];
}

function getLang() {
  const saved = localStorage.getItem("baltiq_lang");
  if (saved && I18N[saved]) return saved;
  const q = new URLSearchParams(location.search).get("lang");
  if (q && I18N[q]) return q;
  return domainDefaultLang();
}

function setLang(code) {
  if (!I18N[code]) return;
  localStorage.setItem("baltiq_lang", code);
  location.reload();
}

function getOverlay() {
  try {
    return JSON.parse(localStorage.getItem("baltiq_i18n_overlay") || "{}");
  } catch {
    return {};
  }
}

function t(key) {
  const lang = getLang();
  const overlay = getOverlay();
  if (overlay[lang] && overlay[lang][key]) return overlay[lang][key];
  return (I18N[lang] && I18N[lang][key]) || (I18N.ru && I18N.ru[key]) || (I18N.en && I18N.en[key]) || key;
}

function applyI18n(root) {
  const box = root || document;
  document.documentElement.lang = getLang();
  box.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  box.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
}

window.BaltiqI18n = { I18N, LANG_META, getLang, setLang, t, applyI18n, langOrder, domainDefaultLang, getOverlay };
